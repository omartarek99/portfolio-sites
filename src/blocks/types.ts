/**
 * The block contract (SPEC §7). Every block lives in `src/blocks/<type>/` and
 * exports a `BlockDefinition` from its `index.ts`.
 *
 * Isomorphic — no server-only imports. Block components render on the server
 * for live sites and on the client inside the editor canvas.
 */
import type { ComponentType } from 'react'
import type { z } from 'zod'
import type { Locale, Localized } from '@/schemas/fields'
import type { FormDefinition } from '@/schemas/forms'
import type { BlockType, Navigation, Page, Section, SiteSettings, Theme } from '@/schemas/site'

/** live: public site · preview: template demo / private preview · editor: editor canvas. */
export type BlockMode = 'live' | 'editor' | 'preview'

export type BlockCategory =
  | 'intro'
  | 'about'
  | 'work'
  | 'social-proof'
  | 'sell'
  | 'contact'
  | 'media'
  | 'content'
  | 'utility'

export type Tier = 'free' | 'pro'

export interface VariantDef {
  id: string
  name: Localized
  description?: Localized
  /** Path under /public, generated by the screenshots script. Optional until M3. */
  thumbnail?: string
  tier: Tier
  /**
   * Full-bleed variant: the section wrapper adds no vertical padding and the
   * variant manages its own spacing (e.g. full-screen heroes).
   */
  bleed?: boolean
}

/* ── Side-panel field configuration ──────────────────────────────────────── */

interface FieldBase {
  /** Dot path relative to `section.content` (or to the list item inside a `list`). */
  path: string
  label: Localized
  help?: Localized
  /** Only show this field for these variants. */
  variants?: string[]
}

export type FieldConfig =
  | (FieldBase & { kind: 'text'; multiline?: boolean; maxLength?: number })
  | (FieldBase & { kind: 'richtext' })
  | (FieldBase & { kind: 'image' })
  | (FieldBase & { kind: 'video' })
  | (FieldBase & { kind: 'button' })
  | (FieldBase & { kind: 'link' })
  | (FieldBase & { kind: 'number'; min?: number; max?: number; step?: number })
  | (FieldBase & { kind: 'boolean' })
  | (FieldBase & { kind: 'select'; options: { value: string; label: Localized }[] })
  | (FieldBase & { kind: 'color' })
  | (FieldBase & { kind: 'icon' })
  | (FieldBase & { kind: 'date' })
  /** string[] */
  | (FieldBase & { kind: 'tags' })
  /** plain, non-localized string (URL, handle, embed code) */
  | (FieldBase & { kind: 'string'; placeholder?: string })
  /** Inline form definition (`FormDefinition`), edited with the form builder. */
  | (FieldBase & { kind: 'form' })
  /** string[] of meeting type ids, picked from the site's booking settings. */
  | (FieldBase & { kind: 'meetingTypes' })
  | (FieldBase & {
      kind: 'list'
      itemLabel: Localized
      /** Path inside the item used as its row title in the panel. */
      titlePath?: string
      fields: FieldConfig[]
      max?: number
      /** New item template. An `id` is generated automatically. */
      defaultItem: Record<string, unknown>
    })

/* ── Manifest ────────────────────────────────────────────────────────────── */

export interface BlockManifest<C = Record<string, unknown>> {
  type: BlockType
  name: Localized
  description?: Localized
  /** Lucide icon name in kebab-case, e.g. "layout-template". */
  icon: string
  category: BlockCategory
  /** At least one. The first is the default variant. */
  variants: VariantDef[]
  /** Content schema. Text fields are Localized. */
  schema: z.ZodType<C>
  /** Bilingual example content shown when a user adds the block. */
  defaultContent: C
  /** Drives the side panel for anything that cannot be edited inline. */
  editableFields: FieldConfig[]
  /** header / footer / announcement: only used in `globalSections`. */
  global?: boolean
}

/* ── Runtime context ─────────────────────────────────────────────────────── */

export interface PostSummary {
  id: string
  slug: string
  title: Localized
  excerpt?: Localized
  coverUrl?: string
  tags: string[]
  publishedAt?: string
}

export interface PublicMeetingType {
  id: string
  name: Localized
  description?: Localized
  durationMin: number
  /** Display only in MVP. */
  price?: { amount: number; currency: string }
  location: 'video' | 'phone' | 'in_person'
}

/**
 * Everything a block may need about the site it renders in.
 * Plain serializable data — it crosses the server→client boundary.
 */
export interface SiteRuntime {
  siteId: string
  /** Subdomain slug of the site, when it has one. */
  slug?: string
  locale: Locale
  locales: Locale[]
  dir: 'ltr' | 'rtl'
  mode: BlockMode
  theme: Theme
  /**
   * URL prefix for every internal link. '' on live sites; e.g.
   * '/demo/aurora' for template demos or '/preview/<token>' for previews.
   */
  basePath: string
  /** Slug of the page being rendered ('' for home). */
  currentSlug: string
  /** True when the current locale is not the default and needs a URL prefix. */
  localePrefix: string
  pages: Pick<Page, 'id' | 'slug' | 'title' | 'type' | 'visibility'>[]
  navigation: Navigation
  settings: SiteSettings
  /** Latest published posts (for Blog list blocks). */
  posts: PostSummary[]
  /** Base path of the blog index page, e.g. 'blog'. Undefined when there is no blog. */
  blogSlug?: string
  meetingTypes: PublicMeetingType[]
  flags: {
    /** "Made with Showcase" badge (Free plan). */
    showBadge: boolean
    /** Pro features available to the site owner's plan. */
    pro: boolean
    /** First-party analytics beacon enabled (live only). */
    analytics: boolean
  }
  /** Origin for public API calls. '' means same origin. */
  apiBase: string
}

export interface BlockContext {
  site: SiteRuntime
  mode: BlockMode
  locale: Locale
  dir: 'ltr' | 'rtl'
  sectionId: string
  /** Zero-based position on the page; lets the first section opt into eager images. */
  index: number
}

export interface BlockProps<C = Record<string, unknown>> {
  /** The full section (style, animation, responsive, anchor). */
  section: Section
  /** `section.content`, validated against the block schema. */
  content: C
  /** The variant to render (already resolved for the current device wrapper). */
  variant: string
  theme: Theme
  locale: Locale
  mode: BlockMode
  siteId: string
  ctx: BlockContext
}

export interface BlockDefinition<C = Record<string, unknown>> {
  manifest: BlockManifest<C>
  Component: ComponentType<BlockProps<C>>
}

/* ── Pre-designed sections (SPEC §7.2) ───────────────────────────────────── */

export interface SectionPreset {
  id: string
  name: Localized
  category: BlockCategory
  blockType: BlockType
  variant: string
  tier: Tier
  /** Template this preset was extracted from, for attribution in the Add tab. */
  fromTemplate?: string
  thumbnail?: string
  style?: Section['style']
  animation?: Section['animation']
  content: Record<string, unknown>
}

/** A manifest / definition with its content type erased, as stored in the registries. */
export type AnyBlockManifest = BlockManifest<Record<string, unknown>>
export type AnyBlockDefinition = BlockDefinition<Record<string, unknown>>

/**
 * Declare a block's manifest with full type-checking of `defaultContent`
 * against the content type, then erase the type for the registry.
 *
 *   export const manifest = defineManifest<HeroContent>({ … })
 */
export function defineManifest<C extends object>(manifest: BlockManifest<C>): AnyBlockManifest {
  return manifest as unknown as AnyBlockManifest
}

/**
 * Pair a manifest with its component. The renderer always validates content
 * against `manifest.schema` before rendering, which is what makes the erased
 * type safe.
 *
 *   export const heroBlock = defineBlock<HeroContent>({ manifest, Component: Hero })
 */
export function defineBlock<C extends object>(definition: {
  manifest: AnyBlockManifest
  Component: ComponentType<BlockProps<C>>
}): AnyBlockDefinition {
  return definition as unknown as AnyBlockDefinition
}

